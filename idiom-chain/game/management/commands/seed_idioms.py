class Command(BaseCommand):
    help = '导入精选演示词库（原创简释，幂等，不删除已有内容）'
    def handle(self, *args, **options):
        rows = [line.split('|', 1) for line in DATA.splitlines()]
        assert len({w for w, _ in rows}) == len(rows)
        assert all(len(w) == 4 and m for w, m in rows)
        for word, meaning in rows:
            Idiom.objects.update_or_create(word=word, defaults={'meaning': meaning})
        self.stdout.write(self.style.SUCCESS(f'已导入 {len(rows)} 条精选成语。'))
