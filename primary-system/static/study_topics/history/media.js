// Resolve local resources from this script so Django topic URLs can have any depth.
// A standalone file:// page continues to use the same local files.
(() => {
  const script = document.currentScript;
  if (!script?.src) return;
  for (const item of [...Object.values(window.HISTORY_MEDIA), ...window.HISTORY_FILMS]) {
    for (const key of ['src', 'poster']) {
      if (item[key]) item[key] = new URL(item[key], script.src).href;
    }
  }
})();
