#!/usr/bin/env python3
"""Extract this prototype's topic container into a deterministic Django template.

No project settings, database, Django application, or files outside this directory
are needed. Run again after editing index.html; --check only checks freshness.
"""

from argparse import ArgumentParser
from html.parser import HTMLParser
from pathlib import Path


VOID_ELEMENTS = {
    "area", "base", "br", "col", "embed", "hr", "img", "input", "link",
    "meta", "param", "source", "track", "wbr",
}


class TopicExtractor(HTMLParser):
    """Find exact source spans without reserializing HTML or SVG markup."""

    def __init__(self, source):
        super().__init__(convert_charrefs=False)
        self.source = source
        self.line_offsets = [0]
        for line in source.splitlines(keepends=True):
            self.line_offsets.append(self.line_offsets[-1] + len(line))
        self.stack = []
        self.targets = []
        self.removals = []

    def source_offset(self):
        line, column = self.getpos()
        return self.line_offsets[line - 1] + column

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        in_main = any(node["tag"] == "main" and node["attrs"].get("id") == "main"
                      for node in self.stack)
        is_topic = "geography-topic" in attrs.get("class", "").split()
        if is_topic and (tag != "div" or not in_main):
            raise ValueError(".geography-topic must be a div inside main#main")
        node = {"tag": tag, "attrs": attrs, "start": self.source_offset(), "topic": is_topic}
        if is_topic:
            self.targets.append(node)
        if tag not in VOID_ELEMENTS:
            self.stack.append(node)

    def handle_startendtag(self, tag, attrs):
        # SVG uses self-closing path/circle elements; they must not affect depth.
        if "geography-topic" in dict(attrs).get("class", "").split():
            raise ValueError(".geography-topic cannot be self-closing")

    def handle_endtag(self, tag):
        if tag in VOID_ELEMENTS:
            return
        if not self.stack or self.stack[-1]["tag"] != tag:
            raise ValueError("Unbalanced HTML near </{}>".format(tag))
        node = self.stack.pop()
        node["end"] = self.source.index(">", self.source_offset()) + 1
        if tag == "a" and node["attrs"].get("href") == "../primary/geo.html":
            self.removals.append((node["start"], node["end"]))

    def extract(self):
        self.feed(self.source)
        self.close()
        if self.stack or len(self.targets) != 1 or "end" not in self.targets[0]:
            raise ValueError("Expected exactly one complete .geography-topic inside main#main")
        start, end = self.targets[0]["start"], self.targets[0]["end"]
        fragment = self.source[start:end]
        for left, right in sorted(self.removals, reverse=True):
            if start <= left < right <= end:
                fragment = fragment[:left - start] + fragment[right - start:]
        if "../primary/" in fragment:
            raise ValueError("The exported topic must not depend on primary/")
        return fragment.strip()


def render_template(source):
    fragment = TopicExtractor(source).extract()
    parts = [
        "{% extends 'base.html' %}",
        "{% load static %}",
        "{# Generated by scripts/export_django.py; edit index.html and regenerate. #}",
        "{% block title %}地理知识精讲 · 乐学堂{% endblock %}",
        "{% block content %}",
        '<link rel="stylesheet" href="{% static \'geo-explorer/styles.css\' %}">',
        '<link rel="stylesheet" href="{% static \'geo-explorer/lab.css\' %}">',
        fragment,
    ]
    for script in ("content.js", "knowledge-core.js", "knowledge-regions.js", "media.js", "diagrams.js", "app.js", "lab.js"):
        parts.append('<script src="{% static \'geo-explorer/' + script + '\' %}" defer></script>')
    parts.append("{% endblock %}")
    return "\n".join(parts) + "\n"


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check freshness without writing files")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    output = root / "django" / "explorer.html"
    try:
        rendered = render_template((root / "index.html").read_text(encoding="utf-8"))
    except ValueError as error:
        parser.exit(1, "Cannot export geography template: {}\n".format(error))
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != rendered:
            parser.exit(1, "Django template is out of date; run scripts/export_django.py\n")
        print("Django template is up to date.")
        return
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(rendered, encoding="utf-8")
    print("Exported {}".format(output))


if __name__ == "__main__":
    main()
